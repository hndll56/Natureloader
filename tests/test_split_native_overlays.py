import importlib.util
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('split_native_overlays', Path(__file__).parents[1] / 'tools/split_native_overlays.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


class SplitTests(unittest.TestCase):
    def test_preserves_functions_and_dispatch(self):
        marker = '/* Generated by PSXRecomp - PlayStation 1 Static Recompiler */\n'
        dispatch_marker = '/* Auto-generated, content-validated overlay dispatch -- do not edit. */'
        bodies = ['void ov_a(CPUState* cpu)\n{\n    cpu->pc = 1;\n}\n',
                  'void ov_b(CPUState* cpu)\n{\n    cpu->pc = 2;\n}\n']
        dispatch = '\nint psx_overlay_dispatch(void) { return 0; }\n'
        with tempfile.TemporaryDirectory() as root:
            source = Path(root) / 'source.c'
            source.write_text(''.join(marker + '#include "psx_runtime.h"\n' + body for body in bodies) + dispatch_marker + dispatch)
            original = source.read_bytes()
            output = Path(root) / 'parts'
            report = module.split(source, output)
            self.assertEqual(report['functions'], 2)
            self.assertEqual(report['banks'], 2)
            for i, body in enumerate(bodies):
                self.assertIn(body, (output / f'bank_{i:02}_000.c').read_text())
            self.assertTrue((output / 'dispatch.c').read_text().endswith(dispatch_marker + dispatch))
            self.assertEqual(source.read_bytes(), original)
            with self.assertRaises(FileExistsError):
                module.split(source, output)

    def test_rejects_unknown_format_without_output(self):
        with tempfile.TemporaryDirectory() as root:
            source = Path(root) / 'source.c'
            source.write_text('unknown output format')
            output = Path(root) / 'parts'
            with self.assertRaises(ValueError):
                module.split(source, output)
            self.assertFalse(output.exists())


if __name__ == '__main__':
    unittest.main()
