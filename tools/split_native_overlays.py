#!/usr/bin/env python3
"""Split PSXRecomp's generated overlay C without changing function bodies.

Development tool only. Input/output contain ROM-derived code and must not be
bundled with the launcher. Output directory must not already exist.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re


def split(source, destination):
    text = source.read_text()
    marker = '/* Auto-generated, content-validated overlay dispatch -- do not edit. */'
    if text.count(marker) != 1:
        raise ValueError('Expected exactly one content-validated dispatch section')
    banks, dispatch = text.split(marker)
    starts = list(re.finditer(r'/\* Generated by PSXRecomp - PlayStation 1 Static Recompiler \*/', banks))
    if not starts:
        raise ValueError('No generated overlay banks found')
    definition = re.compile(r'^void (ov_\w+)\(CPUState\* cpu\)\n\{', re.M)
    outputs = {}
    declarations = []
    function_count = 0
    for index, start in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(banks)
        bank = banks[start.start():end]
        functions = list(definition.finditer(bank))
        if not functions:
            raise ValueError(f'Bank {index} has no recognized function definitions')
        preamble = bank[:functions[0].start()]
        chunks, size, chunk_index = [], 0, 0
        for i, function in enumerate(functions):
            end = functions[i + 1].start() if i + 1 < len(functions) else len(bank)
            body = bank[function.start():end]
            if chunks and size + len(body) > 1_000_000:
                outputs[f'bank_{index:02}_{chunk_index:03}.c'] = preamble + ''.join(chunks)
                chunk_index += 1
                chunks, size = [], 0
            chunks.append(body)
            size += len(body)
            declarations.append(f'extern void {function.group(1)}(CPUState* cpu);\n')
            function_count += 1
        outputs[f'bank_{index:02}_{chunk_index:03}.c'] = preamble + ''.join(chunks)
    if len(set(declarations)) != len(declarations):
        raise ValueError('Duplicate native function definitions')
    outputs['dispatch.c'] = '#include "psx_runtime.h"\n' + ''.join(declarations) + marker + dispatch
    destination.mkdir(parents=True, exist_ok=False)
    for name, contents in outputs.items():
        (destination / name).write_text(contents)
    report = {'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
              'banks': len(starts), 'functions': function_count, 'translationUnits': len(outputs),
              'policy': 'Function bodies and validated dispatch preserved; no interpreter fallback.'}
    (destination / 'manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('destination', type=Path)
    args = parser.parse_args()
    print(json.dumps(split(args.source, args.destination), indent=2))
